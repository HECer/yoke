import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { closeSync, constants, existsSync, fstatSync, lstatSync, mkdirSync, openSync, readFileSync, readSync, realpathSync, readdirSync, writeFileSync } from 'node:fs'
import { isAbsolute, join, relative, resolve, sep } from 'node:path'
import { z } from 'zod'

export const SnapshotFileSchema = z.object({ path: z.string().min(1), hash: z.string().regex(/^[a-f0-9]{64}$/), size: z.number().int().nonnegative() })
export const SnapshotSchema = z.object({ snapshot_id: z.string().regex(/^[a-f0-9]{64}$/), workspace_id: z.string().min(1), root: z.string().min(1), head: z.string().nullable(), files: z.array(SnapshotFileSchema), policy_hash: z.string().length(64), created_at: z.string() })
export type Snapshot = z.infer<typeof SnapshotSchema>
export interface SnapshotPolicy { excludePatterns?: string[]; maxFileBytes?: number; allowNetwork?: boolean }
const MAX_BYTES = 128 * 1024 * 1024
const MAX_FILES = 100_000
const sha256 = (value: string | Uint8Array): string => createHash('sha256').update(value).digest('hex')

function inside(root: string, candidate: string): boolean {
  const rel = relative(root, candidate)
  return rel === '' || (!isAbsolute(rel) && rel !== '..' && !rel.startsWith(`..${sep}`))
}

/** Explicit *, ?, ** grammar; never replace characters generated by another replacement. */
function globToRegExp(pattern: string): RegExp {
  let output = '^'
  const normalized = pattern.replaceAll('\\', '/')
  for (let i = 0; i < normalized.length; i++) {
    const char = normalized[i]!
    if (char === '*' && normalized[i + 1] === '*') {
      i++
      if (normalized[i + 1] === '/') { output += '(?:.*/)?'; i++ } else output += '.*'
    } else if (char === '*') output += '[^/]*'
    else if (char === '?') output += '[^/]'
    else output += char.replace(/[.+^${}()|[\]\\]/g, '\\$&')
  }
  return new RegExp(output + '$')
}
export function excluded(path: string, policy: SnapshotPolicy): boolean {
  const standard = [/(^|\/)\.git(?:\/|$)/, /^\.yoke\/code-intelligence(?:\/|$)/, /(^|\/)\.env(?:\.|$)/, /\.(?:pem|key|p12|pfx)$/i]
  return standard.some(re => re.test(path)) || (policy.excludePatterns ?? []).some(pattern => globToRegExp(pattern).test(path))
}

/** Check all existing ancestors, including metadata paths; leaf checks miss directory symlinks. */
export function assertContainedPath(root: string, candidate: string): string {
  const canonicalRoot = realpathSync(resolve(root)), normalized = candidate.replaceAll('\\', '/')
  if (!normalized || isAbsolute(normalized) || /^[A-Za-z]:/.test(normalized) || normalized.split('/').includes('..') || normalized.includes('\0')) throw new Error('path is outside the permitted workspace')
  const absolute = resolve(canonicalRoot, normalized)
  if (!inside(canonicalRoot, absolute) || absolute === canonicalRoot) throw new Error('path is outside the permitted workspace')
  const rel = relative(canonicalRoot, absolute).replaceAll('\\', '/')
  let current = canonicalRoot
  for (const part of rel.split('/')) {
    current = join(current, part)
    try { if (lstatSync(current).isSymbolicLink()) throw new Error('symbolic links are not allowed in workspace paths') }
    catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') break; throw error }
  }
  return rel
}
export function assertSafePath(root: string, candidate: string, policy: SnapshotPolicy = {}): string {
  const rel = assertContainedPath(root, candidate)
  if (excluded(rel, policy)) throw new Error('path is outside the permitted workspace policy')
  return rel
}
export function metadataPath(root: string, kind: 'snapshots' | 'evidence', id: string): string {
  if (!/^[a-f0-9]{64}$/.test(id)) throw new Error('invalid artifact identifier')
  const rel = `.yoke/code-intelligence/${kind}/${id}.json`
  assertContainedPath(root, rel)
  return join(realpathSync(root), rel)
}
function fallbackFiles(root: string, dir = root, output: string[] = []): string[] {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (['.git', '.yoke', 'node_modules'].includes(entry.name)) continue
    const absolute = join(dir, entry.name)
    if (entry.isDirectory() && !entry.isSymbolicLink()) fallbackFiles(root, absolute, output)
    else if (entry.isFile()) output.push(relative(root, absolute).replaceAll('\\', '/'))
    if (output.length > MAX_FILES) throw new Error('snapshot file budget exceeded')
  }
  return output
}
function workspaceFiles(root: string): { files: string[]; head: string | null } {
  const git = (args: string[]) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] })
  try { git(['rev-parse', '--show-toplevel']) }
  catch (error) {
    if (!String((error as { stderr?: unknown }).stderr).includes('not a git repository')) throw error
    return { files: fallbackFiles(root), head: null }
  }
  const files = [...new Set(git(['ls-files', '-co', '--exclude-standard', '-z']).split('\0').filter(Boolean))]
  let head: string | null = null
  try { head = git(['rev-parse', '--verify', 'HEAD']).trim() || null }
  catch (error) { if (!/Needed a single revision|unknown revision|bad revision|ambiguous argument/.test(String((error as { stderr?: unknown }).stderr))) throw error }
  return { files, head }
}
export function workspaceId(root: string): string { return `workspace-${sha256(realpathSync(resolve(root))).slice(0, 24)}` }
export function snapshotPolicyHash(policy: SnapshotPolicy = {}): string { return sha256(JSON.stringify({ excludePatterns: policy.excludePatterns ?? [], maxFileBytes: policy.maxFileBytes ?? null })) }
export function createSnapshot(workspaceRoot: string, policy: SnapshotPolicy = {}, workspace = workspaceId(workspaceRoot)): Snapshot {
  const root = realpathSync(resolve(workspaceRoot)), listed = workspaceFiles(root)
  if (listed.files.length > MAX_FILES) throw new Error('snapshot file budget exceeded')
  const files: Snapshot['files'] = [], chunk = Buffer.allocUnsafe(128 * 1024)
  let bytes = 0
  for (const candidate of listed.files.sort()) {
    let path: string
    try { path = assertSafePath(root, candidate, policy) } catch { continue }
    const absolute = join(root, path)
    let stat
    try { stat = lstatSync(absolute) } catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') continue; throw error }
    if (!stat.isFile() || (policy.maxFileBytes && stat.size > policy.maxFileBytes)) continue
    if ((bytes += stat.size) > MAX_BYTES) throw new Error('snapshot byte budget exceeded; narrow the permitted files')
    const fd = openSync(absolute, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0)), hash = createHash('sha256')
    try {
      const before = fstatSync(fd)
      if (!before.isFile() || before.ino !== stat.ino || before.dev !== stat.dev) throw new Error('snapshot source changed during opening')
      let offset = 0, count: number
      while ((count = readSync(fd, chunk, 0, chunk.length, offset)) > 0) {
        offset += count
        if (offset > stat.size) throw new Error('snapshot source changed during hashing')
        hash.update(chunk.subarray(0, count))
      }
      const after = fstatSync(fd)
      if (offset !== stat.size || after.size !== before.size || after.mtimeMs !== before.mtimeMs || after.ctimeMs !== before.ctimeMs) throw new Error('snapshot source changed during hashing')
      files.push({ path, hash: hash.digest('hex'), size: offset })
    } finally { closeSync(fd) }
  }
  const policyHash = snapshotPolicyHash(policy)
  const snapshot = SnapshotSchema.parse({ snapshot_id: sha256(JSON.stringify({ workspace, root, head: listed.head, files, policyHash })), workspace_id: workspace, root, head: listed.head, files, policy_hash: policyHash, created_at: new Date().toISOString() })
  const file = metadataPath(root, 'snapshots', snapshot.snapshot_id)
  if (!existsSync(file)) {
    mkdirSync(join(root, '.yoke', 'code-intelligence', 'snapshots'), { recursive: true, mode: 0o700 })
    metadataPath(root, 'snapshots', snapshot.snapshot_id)
    try { writeFileSync(file, JSON.stringify(snapshot) + '\n', { mode: 0o600, flag: 'wx' }) }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error }
  }
  return snapshot
}
export function loadSnapshot(workspaceRoot: string, id: string): Snapshot {
  const root = realpathSync(resolve(workspaceRoot)), file = metadataPath(root, 'snapshots', id)
  if (!existsSync(file)) throw new Error('unknown snapshot')
  if (lstatSync(file).size > 32 * 1024 * 1024) throw new Error('snapshot manifest byte budget exceeded')
  const snapshot = SnapshotSchema.parse(JSON.parse(readFileSync(file, 'utf8')))
  if (snapshot.root !== root || snapshot.snapshot_id !== id) throw new Error('snapshot belongs to another workspace')
  if (sha256(JSON.stringify({ workspace: snapshot.workspace_id, root: snapshot.root, head: snapshot.head, files: snapshot.files, policyHash: snapshot.policy_hash })) !== id) throw new Error('snapshot integrity check failed')
  return snapshot
}
export function currentSnapshotMatches(root: string, snapshot: Snapshot, policy: SnapshotPolicy = {}): boolean { return createSnapshot(root, policy, snapshot.workspace_id).snapshot_id === snapshot.snapshot_id }
export function assertSnapshotCurrent(root: string, snapshot: Snapshot, policy: SnapshotPolicy = {}): void { if (!currentSnapshotMatches(root, snapshot, policy)) throw new Error('snapshot is stale; create a new snapshot before continuing') }
